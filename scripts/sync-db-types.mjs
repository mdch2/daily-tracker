import { readFileSync, writeFileSync, renameSync, rmSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

const target = fileURLToPath(
  new URL('../src/infrastructure/supabase/database.types.ts', import.meta.url),
);
const source = process.argv[2]
  ? resolve(process.argv[2])
  : fileURLToPath(
      new URL(
        '../../daily-tracker-supabase/types/database.types.ts',
        import.meta.url,
      ),
    );
const temporary = target + '.tmp';
try {
  if (resolve(source) === resolve(target))
    throw new Error('Source must be a backend artifact.');
  const types = readFileSync(source, 'utf8');
  if (
    !types.startsWith('// Generated by Supabase CLI. Do not edit.') ||
    !types.includes('export type Database')
  ) {
    throw new Error(
      'The artifact does not identify a Supabase CLI generation.',
    );
  }
  writeFileSync(temporary, types);
  renameSync(temporary, target);
  process.stdout.write(
    'Database types synchronized from the backend artifact.\n',
  );
} catch {
  process.stderr.write(
    'No generated backend types available. Generate them in daily-tracker-supabase first. The previous file was preserved.\n',
  );
  process.exitCode = 1;
} finally {
  rmSync(temporary, { force: true });
}
